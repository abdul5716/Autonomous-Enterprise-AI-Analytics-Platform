"""Render a Report to self-contained HTML (inline SVG charts) and PDF (PNG charts)."""

import io
import json
import re
from datetime import date
from pathlib import Path
from typing import Any
from xml.sax.saxutils import escape

from jinja2 import Environment, PackageLoader, select_autoescape
from markupsafe import Markup
from pydantic import BaseModel
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import (
    Image,
    KeepTogether,
    ListFlowable,
    ListItem,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

from analytics_platform.tools.charts import render_png, render_svg, to_vega_lite
from analytics_platform.tools.report.models import MAX_TABLE_ROWS, Report, ReportTable

FOOTER = "Generated by the Nimbus AI Analytics Platform. Verify figures before external use."
_env = Environment(
    loader=PackageLoader("analytics_platform.tools.report", "templates"),
    autoescape=select_autoescape(["html"]),
)


def fmt_cell(value: Any, column: str = "") -> str:
    if value is None:
        return ""
    if isinstance(value, float):
        if column.endswith("_pct"):
            return f"{value:+.1f}%"
        return f"{value:,.2f}" if abs(value) < 1000 else f"{value:,.0f}"
    if isinstance(value, int) and not isinstance(value, bool):
        return f"{value:,}"
    return str(value)


def short(text: str, limit: int = 160) -> str:
    """Long details (full SQL) stay in report.json; rendered reports show the start."""
    text = " ".join(text.split())
    return text if len(text) <= limit else text[:limit].rsplit(" ", 1)[0] + " ..."


def header(column: str) -> str:
    return column.replace("_pct", " %").replace("_", " ").capitalize()


def _cite_html(text: str) -> Markup:
    escaped = str(escape(text))
    return Markup(re.sub(r"\[(\d+)\]", r'<a class="cite" href="#source-\1">[\1]</a>', escaped))


class ReportFiles(BaseModel):
    report_id: str
    html: Path
    pdf: Path
    json_path: Path


def render_html(report: Report) -> str:
    charts = {}
    for i, section in enumerate(report.sections):
        if section.chart:
            vega = to_vega_lite(section.chart.spec, section.chart.frame())
            charts[i] = Markup(render_svg(vega))  # generated by vl-convert from validated data
    return _env.get_template("report.html").render(
        report=report,
        charts=charts,
        cite=_cite_html,
        fmt=fmt_cell,
        header=header,
        short=short,
        max_rows=MAX_TABLE_ROWS,
        footer=FOOTER,
    )


def _styles() -> dict[str, ParagraphStyle]:
    base = getSampleStyleSheet()
    return {
        "title": base["Title"],
        "meta": ParagraphStyle("meta", parent=base["Normal"], textColor=colors.grey, fontSize=9),
        "h2": base["Heading2"],
        "body": ParagraphStyle("body", parent=base["BodyText"], leading=14),
        "small": ParagraphStyle("small", parent=base["BodyText"], fontSize=8, leading=10),
    }


def _pdf_table(table: ReportTable, style: ParagraphStyle) -> Table:
    rows = table.rows[:MAX_TABLE_ROWS]
    data = [[Paragraph(f"<b>{escape(header(c))}</b>", style) for c in table.columns]]
    data += [
        [Paragraph(escape(fmt_cell(v, c)), style) for v, c in zip(row, table.columns, strict=False)]
        for row in rows
    ]
    t = Table(data, hAlign="LEFT", repeatRows=1)
    t.setStyle(
        TableStyle(
            [
                ("GRID", (0, 0), (-1, -1), 0.3, colors.lightgrey),
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#eef2f7")),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ]
        )
    )
    return t


def render_pdf(report: Report, path: Path) -> None:
    st = _styles()

    def para(text: str, style: str = "body") -> Paragraph:
        return Paragraph(escape(text), st[style])

    def bullets(items: list[str]) -> ListFlowable:
        return ListFlowable([ListItem(para(i)) for i in items], bulletType="bullet", leftIndent=12)

    story: list[Any] = [  # each section's heading, text and chart are kept on one page
        para(report.title, "title"),
        para(
            f"Prepared for {report.prepared_for} on {report.generated_at:%d %B %Y %H:%M} UTC. "
            f"Question: {report.question}",
            "meta",
        ),
        Spacer(1, 0.4 * cm),
        para("Executive summary", "h2"),
        bullets(report.executive_summary),
    ]
    for section in report.sections:
        head: list[Any] = [para(section.heading, "h2")]
        head += [para(p) for p in section.paragraphs]
        if section.bullets:
            head.append(bullets(section.bullets))
        if section.chart:
            png = render_png(to_vega_lite(section.chart.spec, section.chart.frame()), scale=2)
            image = Image(io.BytesIO(png))
            ratio = image.imageHeight / image.imageWidth
            image.drawWidth, image.drawHeight = 16 * cm, 16 * cm * ratio
            head += [Spacer(1, 0.2 * cm), image]
        story.append(KeepTogether(head))
        if section.table:
            if section.table.caption:
                story.append(para(section.table.caption, "meta"))
            story.append(_pdf_table(section.table, st["small"]))
            if len(section.table.rows) > MAX_TABLE_ROWS:
                story.append(
                    para(f"Showing {MAX_TABLE_ROWS} of {len(section.table.rows)} rows.", "meta")
                )
        story.append(Spacer(1, 0.3 * cm))
    for heading, items in (
        ("Assumptions", report.assumptions),
        ("Limitations", report.limitations),
    ):
        if items:
            story += [para(heading, "h2"), bullets(items)]
    story.append(para("Sources", "h2"))
    for n, c in enumerate(report.citations, start=1):
        line = f"[{n}] {c.title} ({c.source_type}: {c.source_id})"
        if c.detail:
            line += f". {short(c.detail)}"
        if c.url:
            line += f". {c.url}"
        story.append(para(line, "small"))

    def footer(canvas: Any, doc: Any) -> None:
        canvas.saveState()
        canvas.setFont("Helvetica", 7)
        canvas.setFillColor(colors.grey)
        canvas.drawString(2 * cm, 1.2 * cm, FOOTER)
        canvas.drawRightString(A4[0] - 2 * cm, 1.2 * cm, f"Page {doc.page}")
        canvas.restoreState()

    SimpleDocTemplate(
        str(path), pagesize=A4, title=report.title, author="Nimbus AI Analytics Platform",
        leftMargin=2 * cm, rightMargin=2 * cm, topMargin=2 * cm, bottomMargin=2 * cm,
    ).build(story, onFirstPage=footer, onLaterPages=footer)  # fmt: skip


def save_report(report: Report, artifacts_dir: Path) -> ReportFiles:
    out = artifacts_dir / "reports" / f"{date.today().isoformat()}-{report.report_id}"
    out.mkdir(parents=True, exist_ok=True)
    files = ReportFiles(
        report_id=report.report_id,
        html=out / "report.html",
        pdf=out / "report.pdf",
        json_path=out / "report.json",
    )
    files.html.write_text(render_html(report))
    render_pdf(report, files.pdf)
    files.json_path.write_text(json.dumps(report.model_dump(mode="json"), indent=2))
    return files
